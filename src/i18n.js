export const STRINGS = { en, it, es }

export function translator(lang) {
  const dict = STRINGS[lang] || en
  return (key, vars) => {
    let s = dict[key] ?? en[key] ?? key
    if (vars) for (const k in vars) s = s.split('{' + k + '}').join(String(vars[k]))
    return s
  }
}
